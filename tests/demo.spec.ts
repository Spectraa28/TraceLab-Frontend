import { test, expect } from '@playwright/test';

test('demo: search, inspect failure, follow evidence, compare and evaluate', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/app');
  await expect(page.getByRole('heading', { name: 'Open your workspace' })).toBeVisible();
  expect(await page.evaluate(() => document.body.scrollWidth <= window.innerWidth)).toBe(true);
  await expect(page.getByText('Need a project key?', { exact: true })).toHaveCount(0);
  await expect(page.locator('body')).not.toContainText('bootstrap_demo.py');
  expect(await page.evaluate(() => document.body.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Explore the demo' }).click();
  await expect(page.getByRole('heading', { name: 'Follow the evidence.' })).toBeVisible();
  await expect(page.locator('.runs-table tbody tr')).toHaveCount(38);
  expect(await page.evaluate(() => document.body.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Needs review', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search runs' }).fill('refund-boundary-31');
  await expect(page.locator('.runs-table tbody tr')).toHaveCount(1);
  await page.locator('.task-link').click();
  await expect(page.getByRole('heading', { name: 'Refund eligible', exact: true })).toBeVisible();
  await expect(page.locator('.step-error')).toBeVisible();
  expect(await page.evaluate(() => document.body.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Open evidence 1 for refund correctness', exact: true }).click();
  await expect(page.locator('.inspector > h2')).not.toHaveText('grounding evaluation');
  await page.locator('.span-row').filter({ hasText: 'grounding evaluation' }).click();
  await page.getByRole('tab', { name: /^Evaluation/ }).click();
  await expect(page.getByText('The refund window is inclusive through day 30.')).toBeVisible();
  await page.locator('.evidence-links button').first().click();
  await expect(page.getByRole('tab', { name: /^Trajectory/ })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('link', { name: 'Evaluations', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Make the fix prove itself.' })).toBeVisible();
  await expect(page.locator('.case-table tbody tr')).toHaveCount(19);
  expect(await page.evaluate(() => document.body.scrollWidth <= window.innerWidth)).toBe(true);
  const row = page.locator('.case-table tr').filter({ hasText: 'refund boundary 31' });
  await row.getByRole('link', { name: 'Compare' }).click();
  await expect(page.getByRole('heading', { name: 'Fewer failing signals. Inspect the evidence.' })).toBeVisible();
  await expect(page.getByText('Your refund was issued.', { exact: true }).first()).toBeVisible();
  expect(await page.evaluate(() => document.body.scrollWidth <= window.innerWidth)).toBe(true);
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.evaluate(() => window.innerWidth));
  expect(errors).toEqual([]);
});
